INSERT INTO products_full (
  id,
  category,
  "itemId",
  name,
  "fullPrice",
  price,
  screen,
  capacity,
  color,
  ram,
  year,
  image,
  "namespaceId",
  "capacityAvailable",
  "colorsAvailable",
  images,
  description,
  resolution,
  processor,
  camera,
  zoom,
  cell
)
SELECT 
  p.id,
  p.category,
  p."itemId",
  p.name,
  p."fullPrice",
  p.price,
  p.screen,
  p.capacity,
  p.color,
  p.ram,
  p.year,
  p.image,
  pi."namespaceId",
  pi."capacityAvailable",
  pi."colorsAvailable",
  pi.images,
  pi.description,
  pi.resolution,
  pi.processor,
  pi.camera,
  pi.zoom,
  pi.cell
FROM products p
LEFT JOIN products_info pi ON p."itemId" = pi.id;